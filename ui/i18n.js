const LS_KEY = "picvert.lang";

function detectDefault() {
  const saved = localStorage.getItem(LS_KEY);
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  // Map browser/system language to one of our supported ones, default to en.
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(nav) ? nav : "en";
}

let current = detectDefault();
const subscribers = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  current = lang;
  localStorage.setItem(LS_KEY, lang);
  subscribers.forEach((fn) => fn(current));
  // Broadcast so the compact-mode capsule (separate window) can update too.
  try {
    const eventNs = window.__TAURI__?.event;
    if (eventNs?.emit) eventNs.emit("picvert:lang-changed", lang);
  } catch {}
}

export function onLangChange(fn) {
  subscribers.add(fn);
  return () => subscribers.delete(fn);
}

export function t(key, params = {}) {
  const dict = translations[current] || translations.en;
  let s = dict[key] || translations.en[key] || key;
  for (const [k, v] of Object.entries(params)) {
    s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
